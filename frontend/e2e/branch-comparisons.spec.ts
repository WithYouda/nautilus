import { expect, test } from '@playwright/test';
import { authorize } from './fact-helpers';

for (const kind of ['conversation', 'discussion']) test(`${kind}: compare, edit, save, source graph and continue`, async ({ page }) => {
  test.setTimeout(90_000);
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const routes = await (await page.request.get(`http://127.0.0.1:${process.env.NAUTILUS_E2E_BACKEND_PORT}/openapi.json`)).json();
  expect(routes.paths['/api/branch-comparisons/{kind}/{identifier}/previews']).toBeTruthy();
  await authorize(page);
  expect((await page.request.put('/api/ai/provider', { data: { display_name: 'Synthetic comparison', base_url: process.env.NAUTILUS_E2E_MOCK_PROVIDER_URL, model: 'mock-review', api_key: 'synthetic-comparison', enabled: true, request_timeout_seconds: 15 } })).ok()).toBeTruthy();
  await page.reload();
  if (kind === 'conversation') {
    await page.getByRole('button', { name: '学习室', exact: true }).click();
    await page.getByRole('button', { name: '新建对话', exact: true }).click();
  } else {
    await page.getByRole('button', { name: '学习首页', exact: true }).first().click();
    if (await (await page.request.get('/api/learning/return-review')).json()) await page.getByRole('button', { name: '创建', exact: true }).click();
    await page.getByLabel('学习目标', { exact: true }).fill('合成目标：分支比较');
    await page.getByRole('button', { name: '我想自己安排' }).click();
    await page.getByLabel('现在先做什么', { exact: true }).fill('合成分支结论任务');
    await page.getByRole('button', { name: '确认这份学习安排' }).click();
    await page.getByRole('button', { name: '进入学习室并开始这项任务' }).click();
    await expect(page.locator('.ai-message--assistant').first()).toBeVisible();
    await page.getByRole('button', { name: '进入验证', exact: true }).click();
    await page.getByRole('button', { name: '开始验证', exact: true }).click();
    await page.getByPlaceholder('写出你的判断、过程或结果').first().fill('合成作答：先定位问题。');
    await page.getByPlaceholder('写出你的判断、过程或结果').nth(1).fill('合成作答：检查边界。');
    await page.getByRole('button', { name: '保存作答并验证' }).click();
    await page.getByRole('region', { name: '验证回看' }).getByRole('article', { name: '第 1 题回看' }).getByRole('button', { name: '讨论这道题' }).click();
  }
  const input = page.getByLabel(kind === 'conversation' ? '输入学习问题' : '继续提问或回答拓展问题', { exact: true });
  async function send(text: string) {
    const posted = page.waitForResponse(response => /\/messages$/.test(response.url()) && response.request().method() === 'POST');
    await input.fill(text); await input.press('Enter');
    const response = await posted; expect(response.ok()).toBeTruthy(); const data = await response.json();
    const id = kind === 'conversation' ? data.run.conversation_id : data.id;
    const path = kind === 'conversation' ? '/api/ai/conversations' : '/api/learning/discussions';
    await expect.poll(async () => { const result = await (await page.request.get(`${path}/${id}`)).json(); return kind === 'conversation' ? result.active_run === null : result.turns.at(-1)?.status === 'succeeded'; }, { timeout: 15_000 }).toBeTruthy();
    await expect(page.getByRole('button', { name: '取消生成', exact: true })).toHaveCount(0);
    return id as string;
  }
  const base = kind === 'conversation' ? '/api/ai/conversations' : '/api/learning/discussions';
  const rootId = await send('合成原思路：先理解问题。');
  const original = await (await page.request.get(`${base}/${rootId}`)).json();
  const answerId = kind === 'conversation' ? original.messages.find((item: { role: string }) => item.role === 'assistant').id : original.turns[0].id;
  const branchResponse = page.waitForResponse(response => response.url().endsWith('/branches') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '从这里创建独立对话' }).first().click();
  expect((await branchResponse).ok()).toBeTruthy();
  const leftId = await send('合成分支甲：先检查边界。');
  const renamePath = (id: string) => `${base}/${id}${kind === 'discussion' ? '/title' : ''}`;
  expect((await page.request.patch(renamePath(leftId), { data: { title: '合成分支甲' } })).ok()).toBeTruthy();
  const added = await page.request.post(`${base}/${rootId}/branches`, { data: { [kind === 'conversation' ? 'message_id' : 'turn_id']: answerId, request_key: crypto.randomUUID() } });
  expect(added.ok()).toBeTruthy(); const branch = await added.json();
  const rightId = kind === 'conversation' ? branch.conversation.id : branch.id;
  expect((await page.request.patch(renamePath(rightId), { data: { title: '合成分支乙' } })).ok()).toBeTruthy();
  await page.getByRole('button', { name: '分支图', exact: true }).click();
  const graph = page.getByRole('dialog', { name: '分支图', exact: true });
  await graph.locator('.branch-map-node').filter({ hasText: '合成分支乙' }).click();
  await graph.getByRole('button', { name: kind === 'conversation' ? '打开对话' : '打开讨论', exact: true }).click();
  async function pickInGraph(first: string, second: string) {
    await graph.getByRole('button', { name: '合并', exact: true }).click();
    const selection = graph.getByRole('group', { name: '图中合并选择' });
    await expect(selection.getByRole('status')).toContainText('已选 0/2');
    await expect(selection.getByRole('button', { name: '整理合并内容' })).toBeDisabled();
    const firstNode = graph.locator(`.branch-map-node[data-node-id="${first}"]`);
    const secondNode = graph.locator(`.branch-map-node[data-node-id="${second}"]`);
    await firstNode.click();
    await expect(firstNode).toHaveAttribute('aria-pressed', 'true');
    await expect(selection.getByRole('status')).toContainText('已选 1/2');
    await firstNode.click();
    await expect(selection.getByRole('status')).toContainText('已选 0/2');
    await firstNode.click(); await secondNode.click();
    await expect(selection.getByRole('status')).toContainText('已选 2/2');
    await expect(graph.locator('.branch-map-pick-badge')).toHaveCount(2);
    await expect(graph.locator('.branch-map-node:not(.is-merge-selected)').first()).toBeDisabled();
    await graph.screenshot({ path: `/tmp/nautilus-graph-pick-${kind}-desktop.png` });
    await page.setViewportSize({ width: 390, height: 900 });
    await expect(selection.getByRole('status')).toContainText('已选 2/2');
    await graph.screenshot({ path: `/tmp/nautilus-graph-pick-${kind}-390.png` });
    await page.setViewportSize({ width: 1280, height: 900 });
    await selection.getByRole('button', { name: '整理合并内容', exact: true }).click();
    const preview = graph.getByRole('region', { name: '分支比较' });
    await expect(preview).toBeVisible();
    await expect(preview.locator('select')).toHaveCount(0);
    return preview;
  }
  await page.getByRole('button', { name: '分支图', exact: true }).click();
  const emptyComparison = await pickInGraph(rootId, rightId);
  await expect(emptyComparison.getByRole('status')).toContainText('内容相同，没有新增内容可合并');
  await expect(emptyComparison.getByRole('button', { name: '创建合并对话', exact: true })).toHaveCount(0);
  await emptyComparison.getByRole('button', { name: '返回图中选取', exact: true }).click();
  await expect(graph.getByRole('group', { name: '图中合并选择' }).getByRole('status')).toContainText('已选 2/2');
  await graph.getByRole('button', { name: '取消合并', exact: true }).click();
  await expect(graph.locator('.branch-map-pick-badge')).toHaveCount(0);
  await graph.getByRole('button', { name: '关闭分支图', exact: true }).click();
  await send('合成分支乙：换一个例子理解。');
  await page.getByRole('button', { name: '分支图', exact: true }).click();
  const compare = await pickInGraph(leftId, rightId);
  await compare.getByLabel('采用：方法的互补', { exact: true }).check();
  await compare.getByLabel('结论：方法的互补', { exact: true }).fill('本人整理：理解问题后，补充边界例子。');
  await compare.getByText('查看原文依据', { exact: true }).click();
  await expect(compare.locator('blockquote')).toHaveCount(2);
  await compare.getByLabel('合并后的主题', { exact: true }).fill('合成两路结论');
  await compare.getByText('查看原文依据', { exact: true }).click();
  await compare.evaluate(element => { element.scrollTop = 0; });
  await graph.screenshot({ path: `/tmp/nautilus-e1-${kind}-desktop.png` });
  await page.setViewportSize({ width: 390, height: 900 });
  await compare.getByRole('button', { name: '创建合并对话' }).scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: `/tmp/nautilus-e1-${kind}-390.png` });
  const accepted = page.waitForResponse(response => response.url().endsWith('/api/branch-comparisons/confirm'));
  await compare.getByRole('button', { name: '创建合并对话' }).click();
  const response = await accepted; expect(response.ok()).toBeTruthy(); const merged = (await response.json()).id;
  await expect(graph).toBeHidden();
  const context = page.getByRole('region', { name: '合并对话起点' });
  await expect(context).toBeVisible();
  await expect(context.getByText('本人整理：理解问题后，补充边界例子。', { exact: true })).toBeVisible();
  await expect(page.getByText('整理这两条分支的结论（已确认）', { exact: true })).toHaveCount(0);
  await expect(context.locator('.merged-context__sources button')).toHaveCount(2);
  await page.screenshot({ path: `/tmp/nautilus-merge-context-${kind}-390.png`, fullPage: true });
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.screenshot({ path: `/tmp/nautilus-merge-context-${kind}-desktop.png`, fullPage: true });
  expect(await send('从结论继续举一个例子。')).toBe(merged);
  await expect(context.locator('.merged-context__content')).not.toHaveAttribute('open', '');
  await context.getByText('这次合并保留的内容', { exact: true }).click();
  await expect(context.getByText('本人整理：理解问题后，补充边界例子。', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '分支图', exact: true }).click();
  await expect(graph.locator('.branch-map-node')).toHaveCount(4);
  await expect(graph.locator('.branch-map-lines path')).toHaveCount(4);
  const incoming = graph.locator(`.branch-map-lines path[data-target-id="${merged}"]`);
  expect(await incoming.evaluateAll(elements => elements.map(element => element.getAttribute('data-source-id')).sort())).toEqual([leftId, rightId].sort());
  await expect(graph.locator(`.branch-map-lines path[data-source-id="${rootId}"][data-target-id="${merged}"]`)).toHaveCount(0);
  await expect(graph.locator('.branch-map-merge-sources button')).toHaveCount(2);
  await graph.screenshot({ path: `/tmp/nautilus-merge-graph-${kind}-desktop.png` });
  await page.setViewportSize({ width: 390, height: 900 });
  await graph.screenshot({ path: `/tmp/nautilus-merge-graph-${kind}-390.png` });
  await graph.getByRole('button', { name: '关闭分支图', exact: true }).click();
  await context.locator('.merged-context__sources button').last().click();
  await expect(input).toBeEnabled();
  expect(errors).toEqual([]);
});
