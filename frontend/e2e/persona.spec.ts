import { expect, test } from '@playwright/test';
import { authorize } from './fact-helpers';

test('persona preview, confirmed versions, restore, export/import and actual coach use', async ({ page }) => {
  test.setTimeout(90_000);
  await authorize(page);
  const configured = await page.request.put('/api/ai/provider', { data: { display_name: 'Synthetic persona', base_url: process.env.NAUTILUS_E2E_MOCK_PROVIDER_URL, model: 'mock-success', api_key: 'synthetic-persona', enabled: true, request_timeout_seconds: 15 } });
  expect(configured.ok()).toBeTruthy();
  await page.getByRole('button', { name: '设置', exact: true }).click();
  const section = page.getByRole('region', { name: '人格设置', exact: true });
  await section.getByRole('button', { name: '新建人格', exact: true }).click();
  await section.getByLabel('人格名称', { exact: true }).fill('合成温和导师');
  await section.getByLabel('人格描述', { exact: true }).fill('温和直接，称呼我同学，鼓励我先做一个小步骤。');
  await section.getByRole('button', { name: '生成风格预览', exact: true }).click();
  await expect(section.getByLabel('人格预览')).toContainText('说话示例');
  expect((await (await page.request.get('/api/personas')).json()).active_id).toBeNull();
  await page.setViewportSize({ width: 390, height: 900 });
  await section.getByLabel('人格预览').scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: '/tmp/nautilus-persona-preview-390.png', fullPage: true });
  await section.getByRole('button', { name: '确认并启用', exact: true }).click();
  await expect(section.getByRole('status')).toContainText('人格已启用');
  let state = await (await page.request.get('/api/personas')).json();
  const originalId = state.active_id;
  await section.getByRole('button', { name: '编辑', exact: true }).click();
  await section.getByLabel('人格名称', { exact: true }).fill('合成第二版导师');
  await section.getByRole('button', { name: '生成风格预览', exact: true }).click();
  await section.getByRole('button', { name: '确认并启用', exact: true }).click();
  await expect(section.getByRole('status')).toContainText('人格已启用');
  await section.getByText('人格详情与历史', { exact: true }).click();
  await section.locator('summary').filter({ hasText: /^第1版/ }).click();
  await section.getByRole('button', { name: '恢复并启用此版', exact: true }).click();
  await expect(section.locator('.persona-current')).toContainText('合成温和导师');
  state = await (await page.request.get('/api/personas')).json();
  expect(state.profiles[0].versions.at(-1).version).toBe(3);
  const download = page.waitForEvent('download');
  await section.getByRole('button', { name: '导出当前人格', exact: true }).click();
  await (await download).saveAs('/tmp/nautilus-persona-test-export.json');
  await section.getByRole('button', { name: '停用', exact: true }).click();
  await expect(section.locator('.persona-current')).toContainText('默认风格');
  await section.getByLabel('导入人格文件', { exact: true }).setInputFiles('/tmp/nautilus-persona-test-export.json');
  await section.getByRole('button', { name: '确认并启用', exact: true }).click();
  await expect(section.getByRole('status')).toContainText('人格已启用');
  state = await (await page.request.get('/api/personas')).json();
  expect(state.profiles).toHaveLength(2);
  await section.getByLabel('已保存的人格', { exact: true }).selectOption(originalId);
  await section.getByRole('button', { name: '启用此人格', exact: true }).click();
  await expect(section.getByRole('status')).toContainText('人格已启用');
  await page.getByRole('button', { name: '关闭设置', exact: true }).click();
  const entry = page.getByRole('region', { name: '学习教练', exact: true });
  await entry.getByLabel('和教练说说今天').fill('今天只有20分钟，有点累。');
  await entry.getByRole('button', { name: '和教练聊聊', exact: true }).click();
  const answer = page.locator('.ai-message--assistant:not(.ai-message--streaming)').first();
  await expect(answer).toBeVisible();
  await answer.getByText('本次模型配置', { exact: true }).click();
  await expect(answer).toContainText('人格：合成温和导师 · 第3版');
  await page.screenshot({ path: '/tmp/nautilus-persona-answer-390.png', fullPage: true });
});
